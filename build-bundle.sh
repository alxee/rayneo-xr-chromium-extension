#!/bin/sh
# Rebuilds injected-bundle.js (the MAIN-world content script) from the
# module sources. Page CSP (YouTube, etc.) blocks chrome-extension://
# script tags, so the bundle is a single classic script injected via the
# manifest instead.
set -e
cd "$(dirname "$0")"

{
  echo "/**"
  echo " * RayNeo WebXR Extension - Injected bundle (MAIN world content script)"
  echo " * Auto-generated from rayneo-hid.js + webxr-polyfill.js + injected.js"
  echo " * + youtube-vr.js."
  echo " * Injected as a MAIN-world content script so page CSP (YouTube, etc.)"
  echo " * cannot block it. Run: ./build-bundle.sh to regenerate."
  echo " * Do not edit this file by hand."
  echo " */"
  sed -e 's/^export class RayNeoHID/class RayNeoHID/' rayneo-hid.js
  echo ""
  sed -e '/^import /d' -e '/^const RAYNEO_DEBUG = false;$/d' -e 's/^export function initRayNeoWebXR/function initRayNeoWebXR/' webxr-polyfill.js
  echo ""
  sed -e '/^import /d' injected.js
  echo ""
  sed -e '/^import /d' youtube-vr.js
} > injected-bundle.js

node --check injected-bundle.js
echo "injected-bundle.js rebuilt OK"
